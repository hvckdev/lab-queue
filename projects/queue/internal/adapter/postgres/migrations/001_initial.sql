CREATE TABLE IF NOT EXISTS subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (length(name) BETWEEN 1 AND 200)
);
CREATE TABLE IF NOT EXISTS sessions (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL REFERENCES subjects(id),
    group_id BIGINT NOT NULL CHECK (group_id > 0),
    group_name TEXT NOT NULL,
    lab_title TEXT NOT NULL CHECK (length(lab_title) BETWEEN 1 AND 200),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    registration_closed BOOLEAN NOT NULL DEFAULT FALSE,
    finished BOOLEAN NOT NULL DEFAULT FALSE,
    next_ticket BIGINT NOT NULL DEFAULT 1 CHECK (next_ticket > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CHECK (ends_at > starts_at),
    CHECK (NOT finished OR registration_closed)
);
CREATE INDEX IF NOT EXISTS sessions_group_start ON sessions(group_id, starts_at);
CREATE INDEX IF NOT EXISTS sessions_teacher_start ON sessions(teacher_id, starts_at);
CREATE TABLE IF NOT EXISTS entries (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES sessions(id),
    student_id BIGINT NOT NULL,
    student_name TEXT NOT NULL,
    ticket_number BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting','called','completed','skipped','cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE(session_id, ticket_number)
);
CREATE UNIQUE INDEX IF NOT EXISTS entries_one_active_student ON entries(session_id, student_id) WHERE status IN ('waiting','called');
CREATE UNIQUE INDEX IF NOT EXISTS entries_one_called ON entries(session_id) WHERE status = 'called';
CREATE INDEX IF NOT EXISTS entries_student ON entries(session_id, student_id, id DESC);
CREATE TABLE IF NOT EXISTS idempotency (
    actor_id BIGINT NOT NULL,
    key TEXT NOT NULL,
    fingerprint TEXT NOT NULL,
    status_code INTEGER NOT NULL,
    response JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY(actor_id, key)
);

